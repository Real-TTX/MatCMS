// Writes ../snapshot.csx: the sensor catalogue bundled with the plugin, so the block is never empty before the first fetch
// (and while cloud.matmon.eu cannot be reached).   node snapshot.mjs [catalog.json | https://cloud.matmon.eu/api/sensor-types]
import fs from 'fs';
const src = process.argv[2] || 'https://cloud.matmon.eu/api/sensor-types';
const json = src.startsWith('http') ? await (await fetch(src)).text() : fs.readFileSync(src, 'utf8');
const parsed = JSON.parse(json);
const compact = JSON.stringify(parsed);
fs.writeFileSync(new URL('../snapshot.csx', import.meta.url),
  `// GENERATED by tools/snapshot.mjs from ${src.startsWith('http') ? src : 'a catalogue file'} (${parsed.sensorTypes.length} sensor types, ${parsed.generatedUtc}) – do not edit by hand.\n` +
  `public static class MmSnapshot\n{\n    public const string Json = @"${compact.replace(/"/g, '""')}";\n}\n`);
console.log(parsed.sensorTypes.length, 'types', parsed.generatedUtc);
