// Builds ../map.csx — the country outlines of Europe as SVG paths, from Natural Earth 1:50m (public domain).
// node build-map.mjs   (needs ne50.geojson next to this file: github.com/nvkelso/natural-earth-vector, geojson/ne_50m_admin_0_countries.geojson)
// Projection: Mercator, x from 25°W to 45°E over 1000 units, y from 72°N down. Coordinates are rounded to 0.1 unit and points closer than
// MIN apart dropped – a map of Europe 1000 units wide needs no more, and the plugin's code stays small.
import fs from 'fs';

const LON0 = -25, LON1 = 45, LAT_TOP = 72, W = 1000, MIN = 1.6;
const K = W / ((LON1 - LON0) * Math.PI / 180);
const merc = (lat) => Math.log(Math.tan(Math.PI / 4 + lat * Math.PI / 360));
const X = (lon) => (lon - LON0) / (LON1 - LON0) * W;
const Y = (lat) => (merc(LAT_TOP) - merc(Math.max(-80, Math.min(84, lat)))) * K;
const H = Y(30);

// Points outside the frame are pulled onto its edge (plus a margin): what lies there is never visible, and Russia alone would
// otherwise be half the file. Clamping a ring to a box keeps it a closed outline of the visible part.
const CLAT0 = 32, CLAT1 = 74, CLON0 = LON0 - 2, CLON1 = LON1 + 2;
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
// Regions that are not a whole country: an outline cut out of the country's by a line of latitude (Sutherland–Hodgman against one
// half-plane). Northern Italy = Italy north of 43.8°N (the Po plain, the Alps, Liguria, Emilia-Romagna, Venetia, South Tyrol).
const REGIONS = [{ iso: 'IT-N', of: 'IT', north: 43.8, de: 'Norditalien', en: 'Northern Italy' }];
const cutNorth = (ring, lat0) => {
  const out = [], inside = ([, lat]) => lat >= lat0;
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i], b = ring[(i + 1) % ring.length];
    if (inside(a)) out.push(a);
    if (inside(a) !== inside(b)) { const t = (lat0 - a[1]) / (b[1] - a[1]); out.push([a[0] + t * (b[0] - a[0]), lat0]); }
  }
  return out;
};
const geo = JSON.parse(fs.readFileSync(new URL('./ne50.geojson', import.meta.url), 'utf8'));
const out = [];
const outline = (rings) => {
  let d = '', box = [Infinity, Infinity, -Infinity, -Infinity];
  for (const ring of rings) {
    if (!ring.some(([lon, lat]) => lon > LON0 - 5 && lon < LON1 + 5 && lat > 28 && lat < LAT_TOP + 4)) continue;
    const pts = [];
    for (const [lon, lat] of ring) {
      const x = Math.round(X(clamp(lon, CLON0, CLON1)) * 10) / 10, y = Math.round(Y(clamp(lat, CLAT0, CLAT1)) * 10) / 10;
      const last = pts[pts.length - 1];
      if (last && Math.hypot(last[0] - x, last[1] - y) < MIN) continue;
      pts.push([x, y]);
    }
    if (pts.length < 4) continue;
    for (const [x, y] of pts) box = [Math.min(box[0], x), Math.min(box[1], y), Math.max(box[2], x), Math.max(box[3], y)];
    d += 'M' + pts.map(([x, y]) => `${x} ${y}`).join('L') + 'Z';
  }
  return { d, box: box.map(Math.round) };
};
const outer = (f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates).map((p) => p[0]);
for (const f of geo.features) {
  const p = f.properties;
  const iso = (p.ISO_A2_EH && p.ISO_A2_EH !== '-99' ? p.ISO_A2_EH : p.ISO_A2) || '';
  if (!/^[A-Z]{2}$/.test(iso)) continue;
  const { d, box } = outline(outer(f));
  if (d) out.push({ iso, de: p.NAME_DE || p.NAME_EN, en: p.NAME_EN, d, box });
  for (const r of REGIONS.filter((r) => r.of === iso)) {
    const o = outline(outer(f).map((ring) => cutNorth(ring, r.north)).filter((ring) => ring.length > 3));
    out.push({ iso: r.iso, de: r.de, en: r.en, d: o.d, box: o.box });
  }
}
out.sort((a, b) => a.iso.localeCompare(b.iso));
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const cs = `// GENERATED by tools/build-map.mjs from Natural Earth 1:50m admin-0 countries (public domain) – do not edit by hand.
// Europe in Mercator, x 25°W–45°E over ${W} units, y from ${LAT_TOP}°N; frame height ${Math.round(H)}.
public static class CovMap
{
    public const int Width = ${W};
    public const int Height = ${Math.round(H)};
    /// <summary>The usual crop: the European mainland from Portugal to the Baltics, Scandinavia's south, the Mediterranean.</summary>
    public static readonly (int X, int Y, int W, int H) Europe = (${Math.round(X(-11))}, ${Math.round(Y(62))}, ${Math.round(X(33) - X(-11))}, ${Math.round(Y(35) - Y(62))});
    public static readonly (string Iso, string De, string En, int X0, int Y0, int X1, int Y1, string Path)[] Countries =
    {
${out.map((c) => `        ("${c.iso}", "${esc(c.de)}", "${esc(c.en)}", ${c.box.join(', ')}, "${c.d}"),`).join('\n')}
    };
}
`;
fs.writeFileSync(new URL('../map.csx', import.meta.url), cs);
console.log(out.length, 'countries,', Math.round(cs.length / 1024), 'KB, height', Math.round(H));
